#!/usr/bin/env python3
"""Author ds4 weight-space patches and multi-level codebooks.

A ds4 weight patch (.wsp) is a line script applied with `ds4 --wsp FILE` or
ds4_wsp_apply_script().  Tensors are row-major matrices: cols is GGUF dim[0]
(matvec inputs), rows is everything else (outputs, times experts).

    scale  <tensor> rows|cols <ranges> <factor>
    mask   <tensor> rows|cols <ranges>
    load   <tensor> <file.f32>        # closed-form matrix, raw f32 rows x cols
    revert <tensor>|*

This tool compiles a JSON description into that script, writing any
closed-form matrices next to it:

    {
      "patches": [
        {"op": "mask",  "tensor": "blk.{L}.ffn_down_shexp.weight",
         "layers": [10, 11], "axis": "cols", "ranges": [[0, 15], 77]},
        {"op": "scale", "tensor": "blk.3.attn_output_b.weight",
         "axis": "rows", "ranges": [[128, 255]], "factor": 0.5},
        {"op": "load",  "tensor": "blk.20.ffn_gate_inp.weight",
         "closed_form": {"kind": "identity", "rows": 256, "cols": 4096}}
      ]
    }

closed_form kinds: identity, zeros, scaled_identity (with "scale"),
projector (removes the unit "direction" vectors from every row:
W = I - sum v v^T, rows == cols), or "npy": "file.npy" (needs numpy).

    python3 gguf-tools/wsp.py compile patch.json -o patch.wsp
    python3 gguf-tools/wsp.py codebook out.ds4c level0.npy level1.npy ...

The codebook command writes the DS4C file read by ds4_mlc_open(): one
K_l x dim f32 matrix per level, coarse first.
"""

import argparse
import json
import math
import os
import struct
import sys


def fmt_ranges(ranges):
    out = []
    for r in ranges:
        if isinstance(r, int):
            out.append(str(r))
        else:
            a, b = r
            if b < a:
                raise ValueError(f"bad range {r}")
            out.append(str(a) if a == b else f"{a}-{b}")
    return ",".join(out)


def closed_form(spec, base_dir):
    """Return (rows, cols, row-major list of floats)."""
    kind = spec.get("kind")
    if "npy" in spec:
        import numpy as np
        m = np.load(os.path.join(base_dir, spec["npy"])).astype("<f4")
        if m.ndim != 2:
            raise ValueError("closed-form .npy must be 2D")
        return m.shape[0], m.shape[1], m
    rows, cols = int(spec["rows"]), int(spec["cols"])
    data = [0.0] * (rows * cols)
    if kind == "zeros":
        pass
    elif kind in ("identity", "scaled_identity"):
        s = float(spec.get("scale", 1.0))
        for i in range(min(rows, cols)):
            data[i * cols + i] = s
    elif kind == "projector":
        if rows != cols:
            raise ValueError("projector must be square")
        for i in range(rows):
            data[i * cols + i] = 1.0
        for v in spec["direction"] if isinstance(spec["direction"][0], list) else [spec["direction"]]:
            if len(v) != cols:
                raise ValueError("direction length must equal cols")
            n = math.sqrt(sum(x * x for x in v)) or 1.0
            u = [x / n for x in v]
            for i in range(rows):
                ui = u[i]
                if ui:
                    for j in range(cols):
                        data[i * cols + j] -= ui * u[j]
    else:
        raise ValueError(f"unknown closed_form kind {kind!r}")
    return rows, cols, data


def write_f32(path, rows, cols, data):
    with open(path, "wb") as f:
        if hasattr(data, "tofile"):
            data.tofile(f)
        else:
            f.write(struct.pack(f"<{rows * cols}f", *data))


def compile_patch(spec, out_path):
    base_dir = os.path.dirname(os.path.abspath(out_path))
    json_dir = spec.get("_dir", base_dir)
    lines = ["# generated by gguf-tools/wsp.py"]
    for n, p in enumerate(spec["patches"]):
        op = p["op"]
        layers = p.get("layers", [None])
        for layer in layers:
            name = p.get("tensor", "*")
            if layer is not None:
                name = name.replace("{L}", str(layer))
            elif "{L}" in name:
                raise ValueError(f"patch {n}: {{L}} needs a layers list")
            if op in ("mask", "scale"):
                axis = p["axis"]
                if axis not in ("rows", "cols"):
                    raise ValueError(f"patch {n}: axis must be rows or cols")
                line = f"{op} {name} {axis} {fmt_ranges(p['ranges'])}"
                if op == "scale":
                    line += f" {float(p['factor']):.9g}"
            elif op == "load":
                rows, cols, data = closed_form(p["closed_form"], json_dir)
                fname = f"wsp_{n}_{name.replace('/', '_')}.f32"
                write_f32(os.path.join(base_dir, fname), rows, cols, data)
                line = f"load {name} {fname}"
            elif op == "revert":
                line = f"revert {name}"
            else:
                raise ValueError(f"patch {n}: unknown op {op!r}")
            lines.append(line)
    with open(out_path, "w") as f:
        f.write("\n".join(lines) + "\n")


def write_codebook(out_path, level_paths):
    import numpy as np
    books = [np.load(p).astype("<f4") for p in level_paths]
    dim = books[0].shape[1]
    if any(b.ndim != 2 or b.shape[1] != dim for b in books):
        raise ValueError("every level must be a K x dim matrix with the same dim")
    with open(out_path, "wb") as f:
        f.write(b"DS4C" + struct.pack("<III", 1, len(books), dim))
        for b in books:
            f.write(struct.pack("<I", b.shape[0]))
            b.tofile(f)


def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)
    c = sub.add_parser("compile", help="JSON patch description -> .wsp script")
    c.add_argument("json")
    c.add_argument("-o", "--output", required=True)
    b = sub.add_parser("codebook", help="per-level .npy codebooks -> DS4C file")
    b.add_argument("output")
    b.add_argument("levels", nargs="+")
    args = ap.parse_args()
    try:
        if args.cmd == "compile":
            with open(args.json) as f:
                spec = json.load(f)
            spec["_dir"] = os.path.dirname(os.path.abspath(args.json))
            compile_patch(spec, args.output)
        else:
            write_codebook(args.output, args.levels)
    except (ValueError, KeyError, OSError) as e:
        print(f"wsp.py: {e}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
